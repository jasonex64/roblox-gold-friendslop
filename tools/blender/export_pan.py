"""Local Blender CLI export, separate from safe-mode MCP modeling.

blender --background --factory-startup --python tools/blender/export_pan.py
Exports only GoldPan, never the user's scene. No Roblox upload is performed.
"""
import hashlib
import json
import sys
from pathlib import Path

import bpy
import bmesh

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gold_pan import build_pan


def export():
    pan = build_pan()
    mesh = pan.data
    bm = bmesh.new()
    bm.from_mesh(mesh)
    assert all(edge.is_manifold for edge in bm.edges), "Pan has an open or non-manifold edge"
    assert bm.calc_volume(signed=True) > 0, "Pan has inward normals or no volume"
    bm.free()
    mesh.calc_loop_triangles()
    triangles = list(mesh.loop_triangles)
    # Roblox general mesh specifications; also the stricter T-018 acceptance ceiling.
    assert 0 < len(triangles) < 20000, "Triangle budget exceeded"
    lines = ["# Generated by tools/blender/export_pan.py; Y up; no timestamps", "mtllib gold_pan.mtl", "o GoldPan"]
    for vertex in mesh.vertices:
        x, y, z = vertex.co
        # Right-handed Z-up -> Y-up rotation; OBJ has no unit metadata.
        lines.append(f"v {x:.6f} {z:.6f} {-y:.6f}")
    lines += ["usemtl GoldPan_Green", "s off"]
    for triangle in triangles:
        lines.append("f " + " ".join(str(index + 1) for index in triangle.vertices))
    destination = ROOT / "assets" / "meshes"
    destination.mkdir(parents=True, exist_ok=True)
    obj_path = destination / "gold_pan.obj"
    obj_path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    (destination / "gold_pan.mtl").write_text(
        "newmtl GoldPan_Green\nKd 0.035 0.240 0.110\nKs 0.250 0.250 0.250\nNs 40\nd 1\n",
        encoding="utf-8", newline="\n",
    )
    report = {"blender": bpy.app.version_string, "vertices": len(mesh.vertices),
              "triangles": len(triangles), "watertight": True,
              "obj_sha256": hashlib.sha256(obj_path.read_bytes()).hexdigest()}
    print("[BLEND-1/2] " + json.dumps(report, sort_keys=True))
    return pan


if __name__ == "__main__":
    export()
